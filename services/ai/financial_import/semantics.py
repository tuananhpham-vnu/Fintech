"""Conservative label checks supplement model proposals; uncertain mappings remain missing."""
import re
import unicodedata

def text(value):
    return re.sub(r'\s+',' ',''.join(c for c in unicodedata.normalize('NFD',value) if not unicodedata.combining(c)).lower().replace('đ','d')).strip()

LABELS={
 'eligible_cash_and_equivalents':r'cash and cash equivalents|现金及现金等价物(?:余额)?',
 'current_assets':r'current assets|tai san ngan han|流动资产合计',
 'current_liabilities':r'current liabilities|no ngan han|流动负债合计',
 'cash':r'^(?:[0-9]+[.)、]\s*)?(?:cash|tien)$|^(?:[一二三四五六七八九十0-9、. ]+)?现金$',
 'unrestricted_short_term_equivalents':r'cash equivalents|cac khoan tuong duong tien|现金等价物',
 'trade_receivables':r'(?:trade|accounts) receivables?|phai thu(?: ngan han)? cua khach hang|phai thu khach hang|应收账款',
 'total_assets':r'total assets|tong(?: cong)? tai san|资产总计|资产总额',
 'total_liabilities':r'total liabilities|tong(?: cong)? no phai tra|^c\s*[-–:]?\s*no phai tra|^no phai tra|负债合计|负债总额',
 'total_equity':r'(?:total )?(?:shareholders|stockholders)[’\x27]? equity|total equity|von chu so huu|所有者权益合计|股东权益合计',
 'interest_bearing_debt':r'total (?:interest.bearing )?debt|interest.bearing (?:debt|borrowings)|vay va no thue tai chinh|有息负债(?:合计|总额)',
 'operating_profit':r'operating (?:income|profit|earnings)|loi nhuan thuan (?:tu )?hoat dong kinh doanh|营业利润|经营利润',
 'depreciation_amortization':r'depreciation.*amorti[sz]ation|khau hao.*(?:phan bo|hao mon)|折旧.*摊销|折旧及摊销',
 'interest_expense':r'interest expense|chi phi lai vay|利息(?:费用|支出)',
 'net_revenue':r'(?:total |net )?revenue|(?:total )?net sales|doanh thu thuan|营业(?:总)?收入',
 'cash_from_operations':r'cash (?:provided by|generated by|generated from|from|used in|provided by \(used in\)) (?:operating activities|operations)|net cash.*operating activities|luu chuyen tien thuan tu hoat dong kinh doanh|经营活动产生的现金流量净额',
}

def semantic_issue(key,label,page_text,basis,country=None):
    label=text(label)
    if not re.search(LABELS[key],label):
        return 'UNSUPPORTED_FINANCIAL_LABEL'
    if key in ('current_assets','current_liabilities') and re.search(r'non[ -]?current|非流动|dai han',label):
        return 'NONCURRENT_SUBTOTAL_NOT_CURRENT'
    if key=='interest_bearing_debt' and re.search(r'net debt|less cash|net of cash|净债务|扣除现金',label):
        return 'NET_DEBT_NOT_GROSS_BORROWINGS'
    if key=='eligible_cash_and_equivalents':
        if country not in ('US','CN') or re.search(r'(?<!un)\brestricted\b|受限|货币资金|restricted cash',label):
            return 'CASH_COMPONENT_NOT_SEPARATE_OR_UNRESTRICTED'
    if country=='CN' and key=='operating_profit' and not re.search(r'(?<!营业)经营利润',label):
        return 'OPERATING_PROFIT_BRIDGE_REQUIRED'
    if key in ('cash','unrestricted_short_term_equivalents') and re.search(r'cash and|tien va|现金及|(?<!un)\brestricted\b|(?<!khong )bi han che|受限|货币资金',label):
        return 'CASH_COMPONENT_NOT_SEPARATE_OR_UNRESTRICTED'
    if key=='unrestricted_short_term_equivalents' and re.search(r'^cash|^tien',label) and re.search(r'and cash|va cac khoan',label):
        return 'CASH_COMPONENT_NOT_SEPARATE_OR_UNRESTRICTED'
    if key=='total_liabilities' and re.search(r'and .*equity|va von|及.*权益',label):
        return 'LIABILITIES_EQUITY_COMBINED'
    if key=='total_equity' and basis=='consolidated' and re.search(r'attributable to|parent|归属于母公司|归属于上市公司',label):
        return 'PARENT_EQUITY_EXCLUDES_NONCONTROLLING_INTEREST'
    if key=='interest_bearing_debt' and re.search(r'short.term|long.term|current|ngan han|dai han|短期|长期|流动',label):
        return 'PARTIAL_DEBT_COMPONENT'
    if key=='depreciation_amortization' and re.search(r'and other|va khac|及其他|等其他',label):
        return 'DA_INCLUDES_OTHER_ITEMS'
    if key=='interest_expense' and re.search(r'\bnet\b|\bpaid\b|da tra|净|支付',label):
        return 'GROSS_INTEREST_EXPENSE_REQUIRED'
    if key=='trade_receivables' and re.search(r'\bgross\b|gia tri gop|账面余额|原值',label):
        return 'NET_TRADE_RECEIVABLES_REQUIRED'
    if key=='trade_receivables' and 'phai thu' in label and not re.search(r'thuan|sau du phong|gia tri ghi so',label):
        return 'NET_TRADE_RECEIVABLES_REQUIRED'
    if key=='operating_profit' and re.search(r'ebitda|before tax|truoc thue|税前|净利润',label):
        return 'OPERATING_PROFIT_PROXY_FORBIDDEN'
    if key=='net_revenue' and 'net sales' in label and re.search(r'total revenues?',text(page_text)):
        return 'REVENUE_SUBTOTAL_REQUIRES_REVIEW'
    return None
